"""Does the repair loop change the layout? For every learner revision the F5 gate kept, the layout of the base video
and of the revision, measured the same way (bench/layout_study.layout_of): layout score, lasting conflicts, timing
faults, broken attachments. Also counts the layout repairs the run logs show.

    python bench/repair_layout.py   -> bench/results/repair-layout/{report.json, report.md}
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "bench")]

import layout_study  # noqa: E402

OUT = ROOT / "bench" / "results" / "repair-layout"
KEYS = ("mvqs_mean", "conflicts", "timing", "broken_attachments")


def main():
    rows = []
    for r in json.loads((ROOT / "bench/results/novel12-stages/rows_F5.json").read_text()):
        if r["learner"]["served"] != "revision":
            continue
        run = ROOT / "runs" / r["topic"]
        plan = json.loads((run / "plan.json").read_text())
        rev = run / "stages" / "F5" / "learner"
        fb = json.loads((rev / "feedback.json").read_text())
        b, l = layout_study.layout_of(run, plan), layout_study.layout_of(rev, plan)
        rows.append({"topic": r["topic"], "sections_edited": fb.get("changed"), "base": {k: b[k] for k in KEYS},
                     "learner": {k: l[k] for k in KEYS}})  # fmt: skip
    log = (ROOT / "bench" / "phase3.log").read_text() if (ROOT / "bench" / "phase3.log").exists() else ""
    fixes = {k: len(re.findall(rf"\[layout\] \w+: {k} fix kept", log)) for k in ("shift", "block", "section")}
    tot = lambda who, k: sum(x[who][k] for x in rows)
    rep = {"revisions": len(rows), "rows": rows, "layout_fixes_kept_in_phase3_log": fixes,
           "totals": {who: {k: tot(who, k) for k in ("conflicts", "timing", "broken_attachments")} for who in ("base", "learner")},
           "worse": sum(x["learner"]["conflicts"] > x["base"]["conflicts"] or
                        x["learner"]["broken_attachments"] > x["base"]["broken_attachments"] for x in rows)}  # fmt: skip
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "report.json").write_text(json.dumps(rep, indent=1))
    lines = ["# Layout of the kept F5 learner revisions against their base videos", "",
             "| Concept | Sections edited | MVQS base → revision | Lasting conflicts | Timing faults | Broken attachments |",
             "|---|---|---|---|---|---|"]  # fmt: skip
    for x in rows:
        b, l = x["base"], x["learner"]
        lines.append(f"| {x['topic']} | {', '.join(x['sections_edited'] or [])} | {b['mvqs_mean']} → {l['mvqs_mean']} | "
                     f"{b['conflicts']} → {l['conflicts']} | {b['timing']} → {l['timing']} | "
                     f"{b['broken_attachments']} → {l['broken_attachments']} |")  # fmt: skip
    lines += ["", f"Revisions with more conflicts or broken attachments than their base: {rep['worse']} of {len(rows)}.",
              f"Layout repairs kept during phase 3 (from the log): {fixes}."]
    (OUT / "report.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    macros = {"RLRevisions": len(rows), "RLWorse": rep["worse"],
              "RLConflictsBase": rep["totals"]["base"]["conflicts"], "RLConflictsLearner": rep["totals"]["learner"]["conflicts"],
              "RLAttachBase": rep["totals"]["base"]["broken_attachments"],
              "RLAttachLearner": rep["totals"]["learner"]["broken_attachments"],
              "RLShiftFixes": fixes["shift"], "RLModelFixes": fixes["block"] + fixes["section"]}  # fmt: skip
    (ROOT / "paper" / "repair_layout_numbers.tex").write_text(
        "% generated by bench/repair_layout.py; do not edit\n"
        + "\n".join(rf"\newcommand{{\{k}}}{{{v}}}" for k, v in macros.items()) + "\n")  # fmt: skip


if __name__ == "__main__":
    main()
