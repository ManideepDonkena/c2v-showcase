"""Write the cost table of every study (paper/costs.tex) from what the runs saved: Claude's token counts in the layout
fixes (runs/*/claude_fixed/fixes.json), in the Claude-student probe caches (runs/**/dv_claude_*.json) and in the Claude
ledger of the generator study (runs/ledger_claude.jsonl). Prices are Anthropic's first-party prices per million tokens.

    python paper/make_costs.py        -> paper/costs.tex, bench/results/costs.json
"""

from __future__ import annotations

import glob
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRICE = {"claude-haiku-5-5": (0.10, 0.50), "claude-sonnet-5-5": (2.0, 10.0), "claude-opus-5-5": (4.0, 20.0)}
NAME = {"claude-haiku-5-5": "Claude Haiku 5.5", "claude-sonnet-5-5": "Claude Sonnet 5.5", "claude-opus-5-5": "Claude Opus 5.5"}


def usd(model, tin, tout):
    pin, pout = PRICE[model]
    return (tin * pin + tout * pout) / 1e6


def usages(obj, acc):
    if isinstance(obj, dict):
        if isinstance(obj.get("input_tokens"), int) and isinstance(obj.get("output_tokens"), int):
            acc["in"] += obj["input_tokens"]
            acc["out"] += obj["output_tokens"]
            acc["calls"] += 1
            return
        for v in obj.values():
            usages(v, acc)
    elif isinstance(obj, list):
        for v in obj:
            usages(v, acc)


def rows():
    out = []
    fx = {"in": 0, "out": 0, "calls": 0, "units": 0}
    for f in glob.glob(str(ROOT / "runs" / "*" / "claude_fixed" / "fixes.json")):
        d = json.loads(Path(f).read_text())
        fx["in"] += d["input_tokens"]
        fx["out"] += d["output_tokens"]
        fx["calls"] += len(d.get("sections") or [])
        fx["units"] += 1
    out.append({"study": "Layout side study: Claude fixes layout and timing", "model": "claude-opus-5-5", **fx,
                "unit": "videos"})  # fmt: skip
    for m in ("claude-haiku-5-5", "claude-sonnet-5-5"):
        acc = {"in": 0, "out": 0, "calls": 0}
        for f in glob.glob(str(ROOT / "runs" / "**" / f"dv_{m.replace('-', '_')}_*.json"), recursive=True):
            usages(json.loads(Path(f).read_text()), acc)
        out.append({"study": "Claude as a second student (NOVEL-12)", "model": m, **acc, "units": acc["calls"],
                    "unit": "quiz requests"})  # fmt: skip
    led = ROOT / "runs" / "ledger_claude.jsonl"
    lines = [json.loads(x) for x in led.read_text().splitlines() if x.strip()] if led.exists() else []
    for fam, m in (("haiku", "claude-haiku-5-5"), ("sonnet", "claude-sonnet-5-5"), ("opus", "claude-opus-5-5")):
        ls = [x for x in lines if x.get("study") == f"claude-gen-{fam}"]
        if ls:
            out.append({"study": "Generator study: Claude plans, codes and repairs", "model": m,
                        "in": sum(x["in"] for x in ls), "out": sum(x["out"] for x in ls), "calls": len(ls),
                        "units": len({x.get("tag") for x in ls}), "unit": "concepts", "usd_logged": sum(x["usd"] for x in ls)})  # fmt: skip
    for r in out:
        r["usd"] = round(r.get("usd_logged") or usd(r["model"], r["in"], r["out"]), 2)
    return out


def main():
    rs = rows()
    total = round(sum(r["usd"] for r in rs), 2)
    (ROOT / "bench" / "results" / "costs.json").write_text(json.dumps({"rows": rs, "total_usd": total}, indent=1))
    k = lambda n: f"{n / 1000:,.0f}k" if n < 1e6 else f"{n / 1e6:.2f}M"
    body = [f"{r['study']} & {NAME[r['model']]} & {r['calls']} & {k(r['in'])} & {k(r['out'])} & \\${r['usd']:.2f} \\\\"
            for r in rs]  # fmt: skip
    tex = [
        "% generated by paper/make_costs.py; do not edit",
        r"\begin{table}[!htbp]\centering\footnotesize",
        r"\caption{What every study cost in paid API use, from the token counts the runs saved. Requests: calls to the "
        r"API. Prices per million tokens (input / output): Haiku 5.5 \$0.10 / \$0.50, Sonnet 5.5 \$2 / \$10, Opus 5.5 "
        r"\$4 / \$20. The local models (planner, coder, student, judge) ran on our own GPUs and cost nothing per token; "
        r"the NOVEL-12 questions were written in a Claude Code session, which is not billed per request.}\label{tab:costs}",
        r"\begin{tabular}{@{}llrrrr@{}}\toprule",
        r"Study & Model & Requests & Tokens in & Tokens out & Cost \\\midrule",
        *body,
        r"\midrule",
        f"Total & & & & & \\${total:.2f} \\\\",
        r"\bottomrule\end{tabular}",
        r"\end{table}",
    ]
    (ROOT / "paper" / "costs.tex").write_text("\n".join(tex) + "\n")
    print("\n".join(body), f"\ntotal ${total:.2f}")


if __name__ == "__main__":
    main()
