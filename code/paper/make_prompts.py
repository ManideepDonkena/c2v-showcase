def tex(s):
    return s.replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def main():
    out = [
        "% generated by paper/make_prompts.py from the prompt strings in the code; do not edit",
        r"Every agent below is one model with one job. Placeholders in braces, such as \texttt{\{topic\}}, are filled in",
        r"at run time; doubled braces are literal braces in the JSON the model must return. The NOVEL-12 TEST questions",
        r"were written once, from the cards only, in a Claude Code session; they are in \texttt{bench/novel/questions.json}.",
        "",
    ]
    for name, model, job, prompts in AGENTS:
        out += [rf"\subsection*{{{name}}}", rf"\textit{{Model:}} {model}. {tex(job)}", ""]
        for title, text in prompts:
            out += [rf"\noindent\textbf{{{title}}}",
                    r"\begin{Verbatim}[breaklines=true,breakanywhere=true,fontsize=\scriptsize,frame=single]",
                    text.strip("\n"), r"\end{Verbatim}", ""]  # fmt: skip
    path = Path(__file__).resolve().parent / "prompts.tex"
    path.write_text("\n".join(out) + "\n")
    print(f"{path}: {sum(len(a[3]) for a in AGENTS)} prompts from {len(AGENTS)} agents")


if __name__ == "__main__":
    main()
