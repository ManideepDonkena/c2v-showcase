from manim import *

class S1(Scene):
    def construct(self):
        # Title
        title = Text("The Seed and the Rule", font_size=36).to_edge(UP, buff=0.2)
        self.play(Write(title))
        self.wait(0.5)

        # Initial seeds
        v1 = MathTex("v(1) = 1", font_size=40)
        v2 = MathTex("v(2) = 3", font_size=40)
        v1.next_to(LEFT, buff=0.5).to_edge(DOWN, buff=0.5)
        v2.next_to(v1, RIGHT, buff=1).to_edge(DOWN, buff=0.5)

        self.play(Write(v1), Write(v2))
        self.wait(1)

        # Arrow from seeds to formula
        arrow = Arrow(start=v1.get_top(), end=v2.get_top(), buff=0.1)
        arrow.shift(0.0 * RIGHT + 0.32 * UP)  # layout: separation vector
        self.play(GrowArrow(arrow))
        self.wait(0.5)

        # Formula box
        formula_box = Rectangle(width=4, height=1.5, color=BLUE, fill_opacity=0.2)
        formula_box.next_to(v2, UP, buff=0.5)
        formula = MathTex("v(n) = v(n-1) + 2 \\cdot v(n-2)", font_size=32)
        formula.move_to(formula_box.get_center())

        formula.shift(0.0 * RIGHT + 1.07 * UP)  # layout: separation vector
        self.play(Write(formula_box), Write(formula))
        self.wait(1)
        
        # Highlight coefficients
        # Ensure we access valid indices
        if len(formula) > 3:
            coeff1 = formula[3].copy()
            coeff1.set_color(YELLOW)
            self.play(
                coeff1.animate.set_fill(YELLOW, opacity=1).scale(1.2),
                run_time=0.5
            )
            self.wait(0.5)
            self.play(
                coeff1.animate.set_fill(WHITE, opacity=1).scale(1/1.2),
                run_time=0.5
            )
        
        if len(formula) > 5:
            coeff2 = formula[5].copy()
            coeff2.set_color(YELLOW)
            self.play(
                coeff2.animate.set_fill(YELLOW, opacity=1).scale(1.2),
                run_time=0.5
            )
            self.wait(0.5)
            self.play(
                coeff2.animate.set_fill(WHITE, opacity=1).scale(1/1.2),
                run_time=0.5
            )

        # Narration text
        narration = Text("A Vorn sequence begins with the seeds 1 and 3.", font_size=24)
        narration.to_edge(DOWN, buff=0.5)
        narration.shift(0.0 * RIGHT + -0.48 * UP)  # layout: separation vector
        self.play(Write(narration))
        self.wait(2)
        self.play(FadeOut(narration))

        narration2 = Text("Every subsequent term is generated by adding the previous term to twice the term before that.", font_size=24)
        narration2.to_edge(DOWN, buff=0.5)
        narration2.shift(0.0 * RIGHT + -0.49 * UP)  # layout: separation vector
        narration2.shift(0.52 * RIGHT + 0.0 * UP)  # layout: separation vector
        self.play(Write(narration2))
        self.wait(2)
        self.play(FadeOut(narration2))

        # Fade out everything
        self.play(
            FadeOut(title),
            FadeOut(v1),
            FadeOut(v2),
            FadeOut(arrow),
            FadeOut(formula_box),
            FadeOut(formula)
        )
        self.wait(0.5)
