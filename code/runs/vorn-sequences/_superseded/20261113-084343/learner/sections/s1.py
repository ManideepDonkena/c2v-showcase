from manim import *

class S1(Scene):
    def construct(self):
        # Title
        title = Text("The Seed and the Rule", font_size=36).to_edge(UP)
        self.play(Write(title))
        self.wait(0.5)

        # Initial seeds
        v1 = MathTex("v(1) = 1", font_size=40)
        v2 = MathTex("v(2) = 3", font_size=40)
        v1.next_to(LEFT, buff=1)
        v2.next_to(RIGHT, buff=1)
        self.play(Write(v1), Write(v2))
        self.wait(1)

        # Arrow connecting seeds to formula
        arrow1 = Arrow(v1.get_bottom(), DOWN, buff=0.2)
        arrow2 = Arrow(v2.get_bottom(), DOWN, buff=0.2)
        self.play(GrowArrow(arrow1), GrowArrow(arrow2))
        self.wait(0.5)

        # Formula box
        formula = MathTex("v(n) = v(n-1) + 2 \\cdot v(n-2)", font_size=40)
        formula_box = SurroundingRectangle(formula, buff=0.3)
        self.play(Write(formula_box), Write(formula))
        self.wait(1)
        # Highlight coefficients
        coeff1 = formula.get_parts_by_tex("1")
        coeff2 = formula.get_parts_by_tex("2")
        self.play(
            *[
                Flash(coeff, color=YELLOW, time_width=0.5)
                for coeff in [coeff1, coeff2]
            ]
        )
        self.wait(1)

        # Narration text
        narration = Text("A Vorn sequence begins with the seeds 1 and 3.", font_size=24)
        narration.to_edge(DOWN)
        self.play(Write(narration))
        self.wait(2)
        self.play(FadeOut(narration))

        narration2 = Text("Every subsequent term is generated by adding the previous term to twice the term before that.", font_size=24)
        narration2.to_edge(DOWN)
        self.play(Write(narration2))
        self.wait(2)
        self.play(FadeOut(narration2))

        # Fade out everything
        self.play(
            FadeOut(title),
            FadeOut(v1),
            FadeOut(v2),
            FadeOut(arrow1),
            FadeOut(arrow2),
            FadeOut(formula_box),
            FadeOut(formula)
        )
        self.wait(0.5)
