        number_52 = VGroup(tens_digit_52, units_digit_52)
        self.play(Write(tens_digit_52), Write(units_digit_52))
        self.wait(0.5)
        self.play(Write(comparison_52))
        self.wait(0.5)
        comparison_52.set_color(GREEN)
        self.play(Indicate(comparison_52, color=GREEN))
        self.wait(0.5)
        number_52_copy = number_52.copy()
        self.play(number_52_copy.animate.set_color(YELLOW).set_opacity(0.8).scale(1.2), run_time=1)
        self.wait(0.5)
        text_52 = Text("Tens > Units", font_size=30).next_to(number_52, DOWN)
        self.play(Write(text_52))
        self.wait(1)

        # Second example: 32
        self.play(FadeOut(title), FadeOut(number_52), FadeOut(comparison_52), FadeOut(text_52))
