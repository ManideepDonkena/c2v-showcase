        title = Text("Introduction to Dapple Numbers", font_size=36).to_edge(UP)
        self.play(Write(title))
        self.wait(0.5)

        # Number line with multiples of 10
        numbers = [10, 20, 30, 40, 50, 60, 70, 80, 90]
        number_mobs = []
        for num in numbers:
            mob = Integer(num, font_size=32)
            number_mobs.append(mob)

        # Animate each number sliding in
        for i, mob in enumerate(number_mobs):
            mob.move_to([i*1.5 - 6, 0, 0])
            mob.shift(-0.69 * RIGHT + 0.0 * UP)  # layout: separation vector
            self.play(
                mob.animate.shift(1.5 * RIGHT),
                run_time=0.3
            )
            # Turn green and label
            self.play(
                mob.animate.set_color(GREEN),
                run_time=0.2
            )
            dapple_label = Text("Dapple", font_size=24).next_to(mob, DOWN)
            dapple_label.shift(-0.4 * RIGHT + 0.0 * UP)  # layout: separation vector
            self.play(Write(dapple_label), run_time=0.3)

