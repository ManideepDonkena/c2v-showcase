        zero_mob = Integer(0, font_size=32).move_to([0, 0, 0])
        self.play(Write(zero_mob))
        self.wait(0.5)
        x_mark = Cross(zero_mob, stroke_width=8, color=RED)
        self.play(Create(x_mark))
        not_dapple_label = Text("Not Dapple (No Tens Digit)", font_size=24).next_to(zero_mob, DOWN)
        self.play(Write(not_dapple_label))
        self.wait(1)

